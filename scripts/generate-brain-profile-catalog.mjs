import { readFileSync, writeFileSync } from "node:fs";
import { keccak256, stringToHex } from "viem";

const sourcePath = new URL(
  "../config/brain-profile-catalog.json",
  import.meta.url,
);
const source = JSON.parse(readFileSync(sourcePath, "utf8"));
const stable = JSON.stringify(source);
const hash = keccak256(stringToHex(stable));

for (const [key, rows] of [
  ["accents", source.accents],
  ["badges", source.badges],
  ["voices", source.voices],
  ["reactions", source.reactions],
]) {
  if (!Array.isArray(rows) || rows.some((row, index) => row.id !== index)) {
    throw new Error(`${key} IDs must be contiguous from zero`);
  }
}

const solidity = `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.28;

library BrainProfileCatalog {
    uint16 internal constant VERSION = ${source.version};
    bytes32 internal constant CATALOG_HASH = ${hash};
    uint8 internal constant ACCENT_COUNT = ${source.accents.length};
    uint8 internal constant BADGE_COUNT = ${source.badges.length};
    uint8 internal constant VOICE_COUNT = ${source.voices.length};
    uint8 internal constant VICTORY_LINE_COUNT = ${source.victoryLineCount};
    uint8 internal constant PANIC_LINE_COUNT = ${source.panicLineCount};
    uint8 internal constant REACTION_COUNT = ${source.reactions.length};
    uint16 internal constant TAGLINE_MAXIMUM_BYTES = ${source.taglineMaximumBytes};
}
`;

const typescript = `// Generated by scripts/generate-brain-profile-catalog.mjs. Do not edit.
export const BRAIN_PROFILE_CATALOG = ${JSON.stringify(source, null, 2)} as const;
export const BRAIN_PROFILE_CATALOG_VERSION = ${source.version} as const;
export const BRAIN_PROFILE_CATALOG_HASH = "${hash}" as const;
`;

writeFileSync(
  new URL(
    "../packages/contracts/src/generated/BrainProfileCatalog.sol",
    import.meta.url,
  ),
  solidity,
);
writeFileSync(
  new URL(
    "../apps/web/lib/brain-profile-catalog.generated.ts",
    import.meta.url,
  ),
  typescript,
);
